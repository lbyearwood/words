update public.knowledge_items item
set pronunciation = backfill.pronunciation
from pronunciation_backfill backfill
where lower(btrim(item.term)) = backfill.normalized_term
  and item.term !~ '[[:space:]]'
  and nullif(btrim(item.pronunciation), '') is null;

alter table public.knowledge_items
  add constraint knowledge_items_single_word_pronunciation_required check (
    term ~ '[[:space:]]' or nullif(btrim(pronunciation), '') is not null
  ) not valid;

